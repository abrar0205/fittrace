import { useMemo } from 'react'
import { Link, useNavigate } from 'react-router-dom'

import { useOverview } from '../api/hooks'
import { SpecHistogram } from '../components/gauges'
import { Plot } from '../components/Plot'
import { Sheet } from '../components/Shell'
import { Empty, ErrorState, Loading, Panel, RunTag } from '../components/ui'
import { dt, fmt, int, pct, signed, time } from '../lib/format'

const SERIES = ['#3b6fd0', '#b04e9a', '#3e9450']

export function Overview() {
  const q = useOverview()
  const nav = useNavigate()
  const o = q.data

  const trend = useMemo(() => {
    if (!o) return null
    const locs = [...new Set(o.trend.map((t) => t.location))]
    const lines = locs.map((loc, i) => {
      const pts = o.trend.filter((t) => t.location === loc)
      return { type: 'scatter', mode: 'lines+markers', name: loc, x: pts.map((p) => p.bucket), y: pts.map((p) => p.mean_deviation_mm),
        line: { color: SERIES[i], width: 2 }, marker: { size: 6, color: SERIES[i], line: { color: '#fafbfb', width: 1.5 } },
        hovertemplate: `${loc}<br>%{x|%d %b %H:00} UTC<br>mean deviation %{y:+.3f} mm<extra></extra>` }
    })
    const oot = locs.map((loc, i) => {
      const pts = o.trend.filter((t) => t.location === loc)
      return { type: 'bar', name: loc, x: pts.map((p) => p.bucket), y: pts.map((p) => p.n_oot), marker: { color: SERIES[i] },
        hovertemplate: `${loc}<br>%{x|%d %b %H:00} UTC<br>%{y} out of tolerance<extra></extra>` }
    })
    return { lines, oot, locs }
  }, [o])

  if (q.isLoading) return <Sheet no={1} title="Line overview"><Loading height={480} /></Sheet>
  if (q.error) return <Sheet no={1} title="Line overview"><div className="panel"><ErrorState error={q.error} /></div></Sheet>
  if (!o?.dataset) {
    return (
      <Sheet no={1} title="Line overview">
        <div className="panel"><Empty title="No dataset imported yet">Run <code>python -m app.cli seed-demo</code> in <code>apps/api</code> to generate, import and measure the demo dataset.</Empty></div>
      </Sheet>
    )
  }
  const ds = o.dataset
  return (
    <Sheet no={1} title="Line overview"
      lede={<>Gap inspection results from the simulated body-in-white line: {int(ds.units)} units, {int(ds.images)} calibrated images, {int(ds.measured)} measured by the pipeline.</>}
      tb={{ dataset: ds.key }}>
      <div className="callout sim">
        {o.provenance?.statement} Production events, faults and images are generated by documented models; see <Link to="/method">Method and evaluation</Link>.
      </div>

      <div className="grid cols-2">
        {o.locations.map((l: any) => (
          <Panel key={l.code} title={<>{l.code} <span className="muted" style={{ fontWeight: 400 }}>{l.name}</span></>}
            aside={`spec ${l.lsl_mm.toFixed(2)} to ${l.usl_mm.toFixed(2)} mm`}>
            <div className="loc-card">
              <div className="loc-figures">
                <div><span className="fig-k">Measured</span><span className="fig-v">{int(l.measured)}</span></div>
                <div><span className="fig-k">Out of tolerance</span><span className={`fig-v ${l.out_of_tolerance ? 'amber' : ''}`}>{int(l.out_of_tolerance)}<small>{pct(l.out_of_tolerance / Math.max(1, l.measured), 1)}</small></span></div>
                <div><span className="fig-k">Mean gap</span><span className="fig-v">{fmt(l.mean_mm, 3)}<small>mm</small></span></div>
                <div><span className="fig-k">Std. deviation</span><span className="fig-v">{fmt(l.sd_mm, 3)}<small>mm</small></span></div>
              </div>
              {l.histogram && <SpecHistogram counts={l.histogram.counts} edges={l.histogram.edges} lsl={l.lsl_mm} usl={l.usl_mm} nominal={l.nominal_mm} />}
              <div className="small muted">
                Distribution of current pipeline measurements; bars outside the specification window are amber.
                {l.failed > 0 && ` ${l.failed} measurements failed and are excluded.`} <Link to={`/analytics?location=${l.code}`}>Control chart for {l.code}</Link>
              </div>
            </div>
          </Panel>
        ))}
      </div>

      {trend && (
        <div className="grid cols-2">
          <Panel title="Mean deviation by hour" aside="deviation from nominal, mm">
            <Plot ariaLabel="Hourly mean gap deviation per location" height={240} data={trend.lines}
              layout={{ showlegend: true, yaxis: { ticksuffix: ' ', zeroline: true, zerolinecolor: '#aeb9c1' }, xaxis: { type: 'date' } }} />
          </Panel>
          <Panel title="Out-of-tolerance inspections by hour" aside="count">
            <Plot ariaLabel="Hourly out-of-tolerance counts per location" height={240} data={trend.oot}
              layout={{ showlegend: true, barmode: 'group', bargap: 0.25, bargroupgap: 0.08, xaxis: { type: 'date' }, yaxis: { rangemode: 'tozero' } }} />
          </Panel>
        </div>
      )}

      <div className="grid cols-3">
        <Panel title="Latest out-of-tolerance" aside={<Link to="/inspect">All inspections</Link>}>
          {o.latest_oot.length ? (
            <table className="table">
              <thead><tr><th>Unit</th><th>Location</th><th className="r">Gap</th><th className="r">Dev.</th></tr></thead>
              <tbody>
                {o.latest_oot.map((r: any) => (
                  <tr key={r.image_id} className="clickable" onClick={() => nav(`/inspect/${r.image_id}`)}>
                    <td className="id"><Link to={`/inspect/${r.image_id}`}>{r.serial}</Link></td><td>{r.location}</td>
                    <td className="r">{fmt(r.gap_mm, 3)}</td><td className="r" style={{ color: 'var(--amber-ink)' }}>{signed(r.deviation_mm)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          ) : <Empty title="No out-of-tolerance results" />}
        </Panel>
        <Panel title="Recent investigations" aside={<Link to="/investigations">All</Link>}>
          {o.recent_investigations.length ? (
            <ul className="list-plain">
              {o.recent_investigations.map((i: any) => (
                <li key={i.id}>
                  <span><Link to={`/investigations/${i.id}`}>#{i.id} {i.serial}</Link> <span className="small muted">{i.location}</span></span>
                  <span className="small">{i.top_explained_fraction ? `${String(i.top_hypothesis).split(' = ').pop()} explains ${pct(i.top_explained_fraction)}` : 'no significant contributor'}</span>
                </li>
              ))}
            </ul>
          ) : <Empty title="No investigations yet">Open an out-of-tolerance inspection and start one from the workbench.</Empty>}
        </Panel>
        <Panel title="Pipelines" aside={<Link to="/pipelines">Monitor</Link>}>
          <ul className="list-plain">
            {o.pipelines.map((p: any) => (
              <li key={p.pipeline}>
                <span><b className="cond">{p.pipeline}</b><br /><span className="small muted">{p.runs} runs, {p.failed_runs} failed, last {time(p.last_started_at)} UTC</span></span>
                <RunTag status={p.last_status} />
              </li>
            ))}
          </ul>
          <div className="small muted" style={{ marginTop: 8 }}>Imported {dt(ds.created_at)}.</div>
        </Panel>
      </div>

      <Panel title="Datasets and provenance">
        <table className="table">
          <thead><tr><th>Key</th><th>Kind</th><th>Provenance</th><th>License</th><th className="r">Units</th><th className="r">Images</th></tr></thead>
          <tbody>
            {o.datasets.map((d) => (
              <tr key={d.id}><td className="id">{d.key}</td><td><span className="tag sim">{d.kind}</span></td><td className="small">{d.provenance}</td>
                <td className="small">{d.license}</td><td className="r">{int(d.units)}</td><td className="r">{int(d.images)}</td></tr>
            ))}
          </tbody>
        </table>
        <p className="small muted" style={{ marginTop: 8 }}>
          NIST box-assembly and Bosch production-line data are documented as separate, unlinked tracks; neither could be downloaded in the build environment, so neither is shown here.
        </p>
      </Panel>
    </Sheet>
  )
}
